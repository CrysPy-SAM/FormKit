import type { FieldConfig, FieldType, FormTheme } from "@formkit/db";

export type FormTemplateField = {
    id: string;
    type: FieldType;
    label: string;
    required?: boolean;
    config?: FieldConfig;
};

export type FormTemplate = {
    id: string;
    name: string;
    description: string;
    category: string;
    icon: string;
    theme: FormTheme;
    fields: FormTemplateField[];
};

function opts(labels: string[]): { id: string; label: string }[] {
    return labels.map((label, i) => ({ id: `opt_${i + 1}`, label }));
}

/** Shorthand for a single-condition "show only if" rule referencing an
 * earlier field's answer — mirrors the shape the builder's conditional
 * logic editor itself writes into field.config.conditionalLogic. */
function showIf(fieldId: string, value: string, operator: "equals" | "not_equals" = "equals") {
    return [{ fieldId, operator, value }];
}

