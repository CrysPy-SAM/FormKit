/** Maps the `icon` string returned by forms.templates.list to a component.
 * Templates ship as plain data over tRPC, so the icon is a key, not a
 * component reference — this is the one place that resolves it. */
const TEMPLATE_ICONS: Record<string, LucideIcon> = {
  Mail,
  MessageSquareHeart,
  CalendarCheck,
  Briefcase,
  Target,
  Smile,
  GraduationCap,
  LifeBuoy,
  BookOpen,
  ShoppingCart,
  UserPlus,
  Building2,
  ClipboardList,
  MessageCircle,
  Quote,
  MonitorPlay,
  Receipt,
  Megaphone,
  UserCheck,
  CalendarOff,
  Users,
  LogOut,
  PartyPopper,
  Presentation,
  Wrench,
  PackageSearch,
  HeartHandshake,
  TrendingUp,
  School,
  Bug,
  CalendarClock,
  UtensilsCrossed,
};

export function getTemplateIcon(key: string): LucideIcon {
  return TEMPLATE_ICONS[key] ?? FileText;
}
